-- Private project chat for creators and accepted teammates.
-- Safe to run more than once in the Supabase SQL Editor.

CREATE TABLE IF NOT EXISTS public.project_chat_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id bigint NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  author_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  body text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT project_chat_messages_body_check CHECK (length(trim(body)) BETWEEN 1 AND 2000)
);

CREATE INDEX IF NOT EXISTS project_chat_messages_project_created_idx
  ON public.project_chat_messages (project_id, created_at DESC);

ALTER TABLE public.project_chat_messages ENABLE ROW LEVEL SECURITY;
GRANT ALL ON TABLE public.project_chat_messages TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.project_chat_messages_id_seq TO service_role;
