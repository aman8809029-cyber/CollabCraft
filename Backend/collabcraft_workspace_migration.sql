-- CollabCraft project lifecycle, work area, and feedback support.
-- Safe to run more than once in the Supabase SQL Editor.

ALTER TABLE public.projects
  ADD COLUMN IF NOT EXISTS status text NOT NULL DEFAULT 'open';

-- Preserve projects that were already inactive before the status column existed.
UPDATE public.projects
SET status = 'closed'
WHERE is_active = false AND status = 'open';

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'projects_status_check'
      AND conrelid = 'public.projects'::regclass
  ) THEN
    ALTER TABLE public.projects
      ADD CONSTRAINT projects_status_check
      CHECK (status IN ('open', 'closed', 'completed'));
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.project_work_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id bigint NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  created_by uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  title varchar(120) NOT NULL,
  description text NOT NULL DEFAULT '',
  storage_path text,
  file_name text,
  mime_type text,
  size_bytes bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT project_work_items_title_check CHECK (length(trim(title)) > 0),
  CONSTRAINT project_work_items_size_check CHECK (size_bytes IS NULL OR size_bytes <= 10485760)
);

CREATE INDEX IF NOT EXISTS project_work_items_project_created_idx
  ON public.project_work_items (project_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.project_tasks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id bigint NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  created_by uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  assigned_to uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  title varchar(120) NOT NULL,
  description text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'todo',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT project_tasks_title_check CHECK (length(trim(title)) > 0),
  CONSTRAINT project_tasks_status_check CHECK (status IN ('todo', 'in_progress', 'done')),
  CONSTRAINT project_tasks_description_check CHECK (length(description) <= 1000)
);

CREATE INDEX IF NOT EXISTS project_tasks_project_status_idx
  ON public.project_tasks (project_id, status, created_at DESC);

CREATE TABLE IF NOT EXISTS public.project_feedback (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id bigint NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  author_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  kind text NOT NULL CHECK (kind IN ('comment', 'suggestion')),
  body text NOT NULL CHECK (length(trim(body)) BETWEEN 1 AND 2000),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS project_feedback_project_created_idx
  ON public.project_feedback (project_id, created_at DESC);

ALTER TABLE public.project_work_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.project_tasks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.project_feedback ENABLE ROW LEVEL SECURITY;

GRANT ALL ON TABLE public.project_work_items TO service_role;
GRANT ALL ON TABLE public.project_tasks TO service_role;
GRANT ALL ON TABLE public.project_feedback TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.project_work_items_id_seq TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.project_tasks_id_seq TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.project_feedback_id_seq TO service_role;

