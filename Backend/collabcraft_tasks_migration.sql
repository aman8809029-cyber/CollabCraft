-- CollabCraft project task board.
-- Safe to run more than once in the Supabase SQL Editor.

CREATE TABLE IF NOT EXISTS public.project_tasks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id bigint NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  created_by uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  assigned_to uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  title varchar(120) NOT NULL,
  description text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'todo',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT project_tasks_title_check CHECK (length(trim(title)) > 0),
  CONSTRAINT project_tasks_status_check CHECK (status IN ('todo', 'in_progress', 'done')),
  CONSTRAINT project_tasks_description_check CHECK (length(description) <= 1000)
);

CREATE INDEX IF NOT EXISTS project_tasks_project_status_idx
  ON public.project_tasks (project_id, status, created_at DESC);

ALTER TABLE public.project_tasks ENABLE ROW LEVEL SECURITY;
GRANT ALL ON TABLE public.project_tasks TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.project_tasks_id_seq TO service_role;
